'use server'

import { PrismaClient } from '@prisma/client'
import { revalidatePath } from 'next/cache'
import { headers } from 'next/headers'

const prisma = new PrismaClient()

async function isAuthenticated() {
  const headersList = await headers()
  const auth = headersList.get('authorization')
  const adminPwd = process.env.ADMIN_PASSWORD
  if (!adminPwd) return false
  if (auth) {
    const [scheme, encoded] = auth.split(' ')
    if (scheme.toLowerCase() === 'basic' && encoded) {
      const [, password] = atob(encoded).split(':')
      return password === adminPwd
    }
  }
  return false
}

export async function addMember(formData: FormData) {
  if (!(await isAuthenticated())) throw new Error("Unauthorized")
  const name = formData.get('name') as string
  if (!name) return

  await prisma.member.create({
    data: {
      name,
      points: 0,
    },
  })

  revalidatePath('/')
  revalidatePath('/admin')
}

export async function recordAttendance(memberId: number, meetingName: string = "Reunião do Rotary") {
  if (!(await isAuthenticated())) throw new Error("Unauthorized")
  const points = 10; // 10 points for attending a meeting

  await prisma.$transaction([
    prisma.pointTransaction.create({
      data: {
        memberId,
        amount: points,
        reason: `Presença: ${meetingName}`,
      }
    }),
    prisma.member.update({
      where: { id: memberId },
      data: { points: { increment: points } }
    })
  ]);

  revalidatePath('/')
  revalidatePath('/admin')
}

export async function addBonusPoints(memberId: number, amount: number, reason: string) {
  if (!(await isAuthenticated())) throw new Error("Unauthorized")
  if (!amount || !reason) return;

  await prisma.$transaction([
    prisma.pointTransaction.create({
      data: {
        memberId,
        amount,
        reason,
      }
    }),
    prisma.member.update({
      where: { id: memberId },
      data: { points: { increment: amount } }
    })
  ]);

  revalidatePath('/')
  revalidatePath('/admin')
}

export async function deleteMember(memberId: number) {
  if (!(await isAuthenticated())) throw new Error("Unauthorized")
  await prisma.$transaction([
    prisma.pointTransaction.deleteMany({
      where: { memberId }
    }),
    prisma.member.delete({
      where: { id: memberId }
    })
  ]);

  revalidatePath('/')
  revalidatePath('/admin')
}
